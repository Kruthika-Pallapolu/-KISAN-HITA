def detect_symptom_group(symptoms_text: str) -> str:
    """Classifies symptom description into one of 4 cautious agronomic groups."""
    st = symptoms_text.strip().lower()
    for group_name in ["yellowing", "spots", "wilting"]:
        keywords = SYMPTOM_KNOWLEDGE_BASE[group_name]["keywords"]
        for kw in keywords:
            if kw.lower() in st:
                return group_name
    return "general"

